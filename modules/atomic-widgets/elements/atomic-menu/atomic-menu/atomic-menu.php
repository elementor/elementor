	/**
	 * Breakpoints the menu can collapse at: the active ones that apply from their width downwards.
	 *
	 * @return Breakpoint[] keyed by breakpoint key, widest last.
	 */
	public static function get_collapsible_breakpoints(): array {
		$breakpoints = Plugin::$instance->breakpoints ?? null;

		if ( ! $breakpoints ) {
			return [];
		}

		$eligible = array_filter(
			$breakpoints->get_active_breakpoints(),
			fn( Breakpoint $breakpoint ) => 'max' === $breakpoint->get_direction()
		);

		uasort( $eligible, fn( Breakpoint $a, Breakpoint $b ) => $a->get_value() <=> $b->get_value() );

		return $eligible;
	}

	private static function get_collapse_breakpoint_keys(): array {
		return [
			Breakpoints_Manager::BREAKPOINT_KEY_MOBILE,
			Breakpoints_Manager::BREAKPOINT_KEY_MOBILE_EXTRA,
			Breakpoints_Manager::BREAKPOINT_KEY_TABLET,
			Breakpoints_Manager::BREAKPOINT_KEY_TABLET_EXTRA,
			Breakpoints_Manager::BREAKPOINT_KEY_LAPTOP,
		];
	}

	public static function get_default_collapse_breakpoint(): string {
		return self::resolve_default_collapse_breakpoint( array_keys( self::get_collapsible_breakpoints() ) );
	}

	public static function resolve_default_collapse_breakpoint( array $available ): string {
		if ( empty( $available ) || in_array( Breakpoints_Manager::BREAKPOINT_KEY_TABLET, $available, true ) ) {
			return Breakpoints_Manager::BREAKPOINT_KEY_TABLET;
		}

		return reset( $available );
	}

	private function get_collapse_breakpoint_options(): array {
		$options = [];

		foreach ( self::get_collapsible_breakpoints() as $key => $breakpoint ) {
			$options[] = [
				'value' => $key,
				'label' => $breakpoint->get_label(),
			];
		}

		return $options;
	}

	/**
	 * CSS that collapses the items behind the toggle, one block per breakpoint the site has.
	 * Lives in a stylesheet (not in the element's atomic styles) because the breakpoint is a setting of
	 * the menu, not a style of it, and the widths are the site's own.
	 */
	public static function get_collapse_css(): string {
		$menu = '.e-menu[data-e-collapse]';
		$toggle = '.e-menu-toggle-base';
		$items = '.e-menu-items-base';

		$css = [
			"{$menu} > {$toggle}{display:none}",
			'.e-menu-toggle-closed-base,.e-menu-toggle-open-base{--e-svg-width:24px;--e-svg-height:24px}',
			".e-menu[data-e-open=\"true\"] > {$toggle} .e-menu-toggle-closed-base{display:none}",
			".e-menu:not([data-e-open=\"true\"]) > {$toggle} .e-menu-toggle-open-base{display:none}",
		];

		foreach ( self::get_collapsible_breakpoints() as $key => $breakpoint ) {
			$scope = ".e-menu[data-e-collapse=\"{$key}\"]:has(> {$toggle})[data-e-ready]";

			$css[] = "@media(max-width:{$breakpoint->get_value()}px){"
				. "{$scope}{flex-wrap:wrap;position:relative}"
				. "{$scope} > {$toggle}{display:flex;order:-1;flex:0 0 auto;width:auto;align-items:center;justify-content:center}"
				. "{$scope} > {$items}{display:none;flex-direction:column;flex-basis:100%;width:100%}"
				. "{$scope}[data-e-open=\"true\"] > {$items}{display:flex}"
				. "{$scope}[data-e-collapsed-position=\"overlay\"] > {$items}{position:absolute;top:100%;inset-inline-start:0;z-index:10}"
				. '}';
		}

		return implode( '', $css );
	}

