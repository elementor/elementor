<?php
namespace Elementor\Modules\AtomicWidgets\Elements\Atomic_Menu\Atomic_Menu;

use Elementor\Modules\AtomicWidgets\Controls\Section;
use Elementor\Modules\AtomicWidgets\Controls\Types\Elements\Menu_Items_Control;
use Elementor\Modules\AtomicWidgets\Controls\Types\Text_Control;
use Elementor\Modules\AtomicWidgets\Elements\Atomic_Menu\Atomic_Menu_Entry\Atomic_Menu_Entry;
use Elementor\Modules\AtomicWidgets\Elements\Atomic_Menu\Atomic_Menu_Item\Atomic_Menu_Item;
use Elementor\Modules\AtomicWidgets\Elements\Atomic_Menu\Atomic_Menu_Items\Atomic_Menu_Items;
use Elementor\Modules\AtomicWidgets\Elements\Atomic_Paragraph\Atomic_Paragraph;
use Elementor\Modules\AtomicWidgets\Elements\Base\Atomic_Element_Base;
use Elementor\Modules\AtomicWidgets\Elements\Base\Has_Element_Template;
use Elementor\Modules\AtomicWidgets\PropTypes\Attributes_Prop_Type;
use Elementor\Modules\AtomicWidgets\PropTypes\Classes_Prop_Type;
use Elementor\Modules\AtomicWidgets\PropTypes\Escaped_Html_Prop_Type;
use Elementor\Modules\AtomicWidgets\PropTypes\Primitives\String_Prop_Type;
use Elementor\Modules\AtomicWidgets\PropTypes\Size_Prop_Type;
use Elementor\Modules\AtomicWidgets\Styles\Style_Definition;
use Elementor\Modules\AtomicWidgets\Styles\Style_Variant;
use Elementor\Modules\Components\PropTypes\Overridable_Prop_Type;

if ( ! defined( 'ABSPATH' ) ) {
	exit; // Exit if accessed directly.
}

class Atomic_Menu extends Atomic_Element_Base {
	use Has_Element_Template;

	const BASE_STYLE_KEY = 'base';
	const ELEMENT_TYPE_MENU = 'e-menu';
	const ELEMENT_TYPE_ITEMS = 'e-menu-items';
	const ELEMENT_TYPE_ENTRY = 'e-menu-entry';
	const ELEMENT_TYPE_ITEM = 'e-menu-item';


	public static $widget_description = 'Create a navigation menu. Structure: e-menu contains e-menu-items (a list of e-menu-entry, each holding one e-menu-item that accepts any V4 element). The structural elements are locked and generated by the model.';

	public function __construct( $data = [], $args = null ) {
		parent::__construct( $data, $args );
		$this->meta( 'is_container', true );
		$this->meta( 'is_compound', true );
	}

	public static function get_type() {
		return self::ELEMENT_TYPE_MENU;
	}

	public static function get_element_type(): string {
		return self::ELEMENT_TYPE_MENU;
	}

	public function get_title() {
		return esc_html__( 'Menu', 'elementor' );
	}

	public function get_keywords() {
		return [ 'ato', 'atom', 'atoms', 'atomic', 'nav', 'navigation' ];
	}

	public function get_icon() {
		return 'eicon-nav-menu';
	}

	public static function get_computed_html_tag( array $settings ): string {
		return 'nav';
	}

	protected static function define_props_schema(): array {
		return [
			'classes' => Classes_Prop_Type::make()
				->default( [] ),
			'menu-name' => String_Prop_Type::make()
				->default( esc_html__( 'Menu', 'elementor' ) )
				->description( 'Accessible label of the nav element.' ),
			'attributes' => Attributes_Prop_Type::make()->meta( Overridable_Prop_Type::ignore() ),
		];
	}

	protected function define_atomic_controls(): array {
		return [
			Section::make()
				->set_label( __( 'Content', 'elementor' ) )
				->set_id( 'content' )
				->set_items( [
					Menu_Items_Control::make()
						->set_label( __( 'Menu items', 'elementor' ) )
						->set_meta( [
							'layout' => 'custom',
						] ),
					Text_Control::bind_to( 'menu-name' )
						->set_label( __( 'Menu name', 'elementor' ) ),
				] ),
			Section::make()
				->set_label( __( 'Settings', 'elementor' ) )
				->set_id( 'settings' )
				->set_items( [
					Text_Control::bind_to( '_cssid' )
						->set_label( __( 'ID', 'elementor' ) )
						->set_meta( $this->get_css_id_control_meta() ),
				] ),
		];
	}

	protected function define_base_styles(): array {
		return [
			static::BASE_STYLE_KEY => Style_Definition::make()
				->add_variant(
					Style_Variant::make()
						->add_props( [
							'display' => String_Prop_Type::generate( 'flex' ),
							'padding' => Size_Prop_Type::generate( [
								'size' => 0,
								'unit' => 'px',
							] ),
						] )
				),
		];
	}

	protected function define_allowed_child_types() {
		return [ self::ELEMENT_TYPE_ITEMS ];
	}

	private function get_default_entry_names(): array {
		return [
			esc_html__( 'Home', 'elementor' ),
			esc_html__( 'Products', 'elementor' ),
			esc_html__( 'About', 'elementor' ),
			esc_html__( 'Contact', 'elementor' ),
		];
	}

	protected function define_default_children() {
		$entries = [];

		foreach ( $this->get_default_entry_names() as $name ) {
			$entries[] = Atomic_Menu_Entry::generate()
				->editor_settings( [ 'title' => $name ] )
				->children( [
					Atomic_Menu_Item::generate()
						->children( [
							Atomic_Paragraph::generate()
								->settings( [
									'paragraph' => Escaped_Html_Prop_Type::generate( $name ),
									'tag' => String_Prop_Type::generate( 'span' ),
								] )
								->build(),
						] )
						->build(),
				] )
				->build();
		}

		return [
			Atomic_Menu_Items::generate()
				->children( $entries )
				->build(),
		];
	}

	protected function get_templates(): array {
		return [
			'elementor/elements/atomic-menu' => __DIR__ . '/atomic-menu.html.twig',
		];
	}
}
