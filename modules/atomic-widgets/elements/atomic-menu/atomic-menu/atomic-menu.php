	private function get_default_entry_names(): array {
		return [
			esc_html__( 'Home', 'elementor' ),
			esc_html__( 'Products', 'elementor' ),
			esc_html__( 'About', 'elementor' ),
			esc_html__( 'Contact', 'elementor' ),
		];
	}

	protected function define_default_children() {
		$entries = [];

		foreach ( $this->get_default_entry_names() as $name ) {
			$entries[] = Atomic_Menu_Entry::generate()
				->editor_settings( [ 'title' => $name ] )
				->children( [
					Atomic_Menu_Item::generate()
						->children( [
							Atomic_Paragraph::generate()
								->settings( [
									'paragraph' => Escaped_Html_Prop_Type::generate( $name ),
									'tag' => String_Prop_Type::generate( 'span' ),
								] )
								->build(),
						] )
						->build(),
				] )
				->build();
		}

		return [
			Atomic_Menu_Items::generate()
				->children( $entries )
				->build(),
			Atomic_Menu_Toggle::generate()
				->children( [
					Atomic_Menu_Toggle_Closed::generate()
						->hydrate_default_children( true )
						->build(),
					Atomic_Menu_Toggle_Open::generate()
						->hydrate_default_children( true )
						->build(),
				] )
				->build(),
		];
	}

	public function get_script_depends() {
		$global_depends = parent::get_script_depends();

		if ( Plugin::$instance->preview->is_preview_mode() ) {
			return array_merge( $global_depends, [ 'elementor-menu-handler', 'elementor-menu-preview-handler' ] );
		}

		return array_merge( $global_depends, [ 'elementor-menu-handler' ] );
	}

	public function register_frontend_handlers() {
		$assets_url = ELEMENTOR_ASSETS_URL;
		$min_suffix = ( Utils::is_script_debug() || Utils::is_elementor_tests() ) ? '' : '.min';

		foreach ( [ 'menu-handler', 'menu-preview-handler' ] as $handle ) {
			wp_register_script(
				"elementor-{$handle}",
				"{$assets_url}js/{$handle}{$min_suffix}.js",
				[ Frontend_Assets_Loader::FRONTEND_HANDLERS_HANDLE, Frontend_Assets_Loader::ALPINEJS_HANDLE ],
				ELEMENTOR_VERSION,
				true
			);
		}
	}

