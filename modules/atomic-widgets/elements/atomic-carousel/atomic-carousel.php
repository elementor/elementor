/**
 * V4 Carousel root element (ED-25236 / ED-25237).
 *
 * Engine is Embla Carousel, bundled into `carousel-handler.js`. Embla is headless: it owns
 * scroll physics and snap points only, while every visible node below is a real V4 element the
 * user can style and fill.
 *
 * Three deliberate deviations from the spec, each recorded in
 * docs/carousel_v4_library_research.md with the measurement that motivated it:
 *  - `transition_speed` is stored in milliseconds and mapped to Embla's `duration` in the
 *    handler, so the saved value never carries an engine-specific physics constant.
 *  - The autoplay pause/play button is generated by the handler rather than being an eighth
 *    persisted sub-element, because the saved child tree cannot be migrated today.
 *  - Arrow base styles use logical inset properties so they follow `dir` in RTL.
 */
class Atomic_Carousel extends Atomic_Element_Base {
	use Has_Element_Template;

	const BASE_STYLE_KEY = 'base';

	const ELEMENT_TYPE_VIEWPORT = 'e-carousel-viewport';
	const ELEMENT_TYPE_CONTAINER = 'e-carousel-container';
	const ELEMENT_TYPE_SLIDE = 'e-carousel-slide';
	const ELEMENT_TYPE_ARROW_PREV = 'e-carousel-arrow-prev';
	const ELEMENT_TYPE_ARROW_NEXT = 'e-carousel-arrow-next';
	const ELEMENT_TYPE_PAGINATION = 'e-carousel-pagination';

	const DEFAULT_SLIDE_COUNT = 4;

	public static $widget_description = 'A carousel of slides with arrow navigation and dot pagination. REQUIRED child: e-carousel-viewport, which contains a single e-carousel-container holding the e-carousel-slide elements. Optional direct children: e-carousel-arrow-prev, e-carousel-arrow-next (each wraps any element as the arrow content) and e-carousel-pagination (dots are generated at runtime). Arrows and pagination are siblings of the viewport, never children of it, so dragging a slide never starts on an arrow.';

	public function __construct( $data = [], $args = null ) {
		parent::__construct( $data, $args );
		$this->meta( 'is_container', true );
	}

	public static function get_type() {
		return 'e-carousel';
	}

	public static function get_element_type(): string {
		return 'e-carousel';
	}

	public function get_title() {
		return esc_html__( 'Carousel', 'elementor' );
	}

	public function get_keywords() {
		return [ 'ato', 'atom', 'atoms', 'atomic', 'carousel', 'slider', 'slides' ];
	}

	public function get_icon() {
		return 'eicon-nested-carousel';
	}

	protected static function define_props_schema(): array {
		$when_autoplay_on = Dependency_Manager::make()
			->where( [
				'operator' => 'eq',
				'path' => [ 'autoplay' ],
				'value' => true,
			] )
			->get();

		// Fade stacks every slide on top of each other, so "how many are visible" and
		// "how many to advance" stop being meaningful. Hide both while fade is selected.
		$when_transition_is_slide = Dependency_Manager::make()
			->where( [
				'operator' => 'eq',
				'path' => [ 'transition_type' ],
				'value' => 'slide',
			] )
			->get();

		return [
			'classes' => Classes_Prop_Type::make()->default( [] ),
			'transition_type' => String_Prop_Type::make()
				->enum( [ 'slide', 'fade' ] )
				->default( 'slide' )
				->description( 'How the carousel moves between slides. `slide` scrolls horizontally, `fade` cross-fades and forces a single slide per view.' ),
			'slides_per_view' => Number_Prop_Type::make()
				->default( 3 )
				->set_dependencies( $when_transition_is_slide )
				->meta( Dynamic_Prop_Type::ignore() )
				->description( 'How many slides are visible at once, 1 to 10.' ),
			'slides_to_scroll' => Number_Prop_Type::make()
				->default( 1 )
				->set_dependencies( $when_transition_is_slide )
				->meta( Dynamic_Prop_Type::ignore() )
				->description( 'How many slides each arrow or dot click advances, 1 to 10.' ),
			'loop' => Boolean_Prop_Type::make()
				->default( false )
				->description( 'Scroll past the last slide back to the first. Implemented by repositioning slides, so no slide is ever duplicated.' ),
			'autoplay' => Boolean_Prop_Type::make()
				->default( false )
				->description( 'Advance slides automatically. Always off inside the editor.' ),
			'autoplay_delay' => Number_Prop_Type::make()
				->default( 5000 )
				->set_dependencies( $when_autoplay_on )
				->meta( Dynamic_Prop_Type::ignore() )
				->meta( 'suffix', 'MS' )
				->description( 'Milliseconds each slide stays on screen while autoplay runs.' ),
			'pause_on_hover' => Boolean_Prop_Type::make()
				->default( true )
				->set_dependencies( $when_autoplay_on )
				->description( 'Pause autoplay while the pointer is over the carousel.' ),
			'pause_on_interaction' => Boolean_Prop_Type::make()
				->default( true )
				->set_dependencies( $when_autoplay_on )
				->description( 'Pause autoplay once the visitor drags or clicks their way through the slides.' ),
			'show_autoplay_button' => Boolean_Prop_Type::make()
				->default( true )
				->set_dependencies( $when_autoplay_on )
				->description( 'Show a pause/play button. Required by WCAG 2.2.2 whenever content moves on its own.' ),
			// Milliseconds, not Embla's `duration`. Embla's unit is a spring constant where the
			// documented usable band is 20-60 and 100 produces a ~9 second transition, so the
			// handler converts. Keeping ms here also keeps the engine out of the saved data.
			'transition_speed' => Number_Prop_Type::make()
				->default( 600 )
				->meta( Dynamic_Prop_Type::ignore() )
				->meta( 'suffix', 'MS' )
				->description( 'How long one transition takes, in milliseconds.' ),
			'show_arrows' => Boolean_Prop_Type::make()
				->default( true )
				->description( 'Show the previous/next arrow elements. Turning this off removes them from the DOM and the Structure panel.' ),
			'show_pagination' => Boolean_Prop_Type::make()
				->default( true )
				->description( 'Show the pagination dots. Turning this off removes them from the DOM and the Structure panel.' ),
			'attributes' => Attributes_Prop_Type::make()->meta( Overridable_Prop_Type::ignore() ),
		];
	}

	protected function define_atomic_controls(): array {
		return [
			Section::make()
				->set_label( __( 'Content', 'elementor' ) )
				->set_id( 'content' )
				->set_items( [
