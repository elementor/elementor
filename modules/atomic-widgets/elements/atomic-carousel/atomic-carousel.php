	}

	protected function define_base_styles(): array {
		return [
			static::BASE_STYLE_KEY => Style_Definition::make()
				->add_variant(
					Style_Variant::make()
						->add_props( [
							'position' => String_Prop_Type::generate( 'relative' ),
						] )
				),
		];
	}

	protected function define_default_children() {
		$slides = [];

		// Four slides at three per view means the fourth sits off-screen, so the arrows and dots
		// are live the moment the element is dropped instead of looking broken.
		foreach ( range( 1, self::DEFAULT_SLIDE_COUNT ) as $i ) {
			$slides[] = Atomic_Carousel_Slide::generate()
				->editor_settings( [
					/* translators: %d: Slide number. */
					'title' => sprintf( esc_html__( 'Slide %d', 'elementor' ), $i ),
					'initial_position' => $i,
				] )
				->build();
		}

		$viewport = Atomic_Carousel_Viewport::generate()
			->meta( [ 'required' => true ] )
			->editor_settings( [
				'title' => esc_html__( 'Viewport', 'elementor' ),
			] )
			->children( [
				Atomic_Carousel_Container::generate()
					->meta( [ 'required' => true ] )
					->editor_settings( [
						'title' => esc_html__( 'Slides', 'elementor' ),
					] )
					->children( $slides )
					->build(),
			] )
			->build();

		return [
			$viewport,
			Atomic_Carousel_Arrow_Prev::build_default_element(),
			Atomic_Carousel_Arrow_Next::build_default_element(),
			Atomic_Carousel_Pagination::build_default_element(),
		];
	}

	/**
	 * `show_arrows` and `show_pagination` attach and detach real child elements rather than
	 * hiding them with CSS, so a hidden arrow costs nothing in the DOM or the Structure panel.
	 *
	 * The stash is session storage only: detaching, saving and returning in a later session
	 * restores `default_model`, not the visitor's customised arrow content. That trade-off is
	 * inherited from e-background-video and is flagged as R2 in the research doc.
	 */
	protected function define_children_dependencies(): array {
		$shown = fn( string $prop ) => Dependency_Manager::make()->where( [
			'operator' => 'ne',
			'path' => [ $prop ],
			'value' => false,
		] );

		return [
			Child_Dependency::for( self::ELEMENT_TYPE_ARROW_PREV )
				->when( $shown( 'show_arrows' ) )
				->position( Element_Position::last() )
				->stash( true )
				->default_model(
					Element_Builder::make( self::ELEMENT_TYPE_ARROW_PREV )
						->is_locked( true )
						->hydrate_default_children( true )
						->build()
				),
			Child_Dependency::for( self::ELEMENT_TYPE_ARROW_NEXT )
				->when( $shown( 'show_arrows' ) )
				->position( Element_Position::last() )
				->stash( true )
				->default_model(
					Element_Builder::make( self::ELEMENT_TYPE_ARROW_NEXT )
						->is_locked( true )
						->hydrate_default_children( true )
						->build()
				),
			Child_Dependency::for( self::ELEMENT_TYPE_PAGINATION )
				->when( $shown( 'show_pagination' ) )
				->position( Element_Position::last() )
				->stash( true )
				->default_model(
					Element_Builder::make( self::ELEMENT_TYPE_PAGINATION )
						->is_locked( true )
						->build()
				),
		];
	}

	protected function define_allowed_child_types() {
		return [
			self::ELEMENT_TYPE_VIEWPORT,
			self::ELEMENT_TYPE_ARROW_PREV,
			self::ELEMENT_TYPE_ARROW_NEXT,
			self::ELEMENT_TYPE_PAGINATION,
		];
	}

	public function get_script_depends() {
		$global_depends = parent::get_script_depends();

		return array_merge( $global_depends, [ 'elementor-carousel-handler' ] );
	}

	public function register_frontend_handlers() {
		$assets_url = ELEMENTOR_ASSETS_URL;
		$min_suffix = ( Utils::is_script_debug() || Utils::is_elementor_tests() ) ? '' : '.min';

		wp_register_script(
			'elementor-carousel-handler',
			"{$assets_url}js/carousel-handler{$min_suffix}.js",
			[ Frontend_Assets_Loader::FRONTEND_HANDLERS_HANDLE ],
			ELEMENTOR_VERSION,
			true
		);
	}

	protected function build_template_context(): array {
		$settings = $this->get_atomic_settings();

		return array_merge( $this->build_base_template_context(), [
			'is_editor' => Plugin::$instance->preview->is_preview_mode(),
			'aria_label' => esc_attr__( 'Carousel', 'elementor' ),
			'slides_per_view' => 'fade' === ( $settings['transition_type'] ?? 'slide' )
				? 1
				: (int) ( $settings['slides_per_view'] ?? 3 ),
		] );
	}

	protected function get_templates(): array {
		return [
			'elementor/elements/atomic-carousel' => __DIR__ . '/atomic-carousel.html.twig',
		];
	}
}
